/// Maps a 32-byte nullifier (an Ed25519 public key) onto G1.
///
/// This is the `Y = H(spend_pk)` of the protocol. The contract always derives
/// `Y` itself — a caller-supplied `Y` would let anyone pick a point they know
/// a signature for.
pub fn hash_nullifier_to_g1(env: &Env, nullifier: &BytesN<32>) -> Bls12381G1Affine {
    let msg = Bytes::from(nullifier.clone());
    let dst = Bytes::from_slice(env, HASH_TO_G1_DST);
    env.crypto().bls12_381().hash_to_g1(&msg, &dst)
}

/// Checks that a G2 public key is a well-formed point in the prime-order
/// subgroup. Called once at construction so the redeem path never has to.
pub fn is_valid_mint_pk(env: &Env, pk_mint: &BytesN<192>) -> bool {
    let bls = env.crypto().bls12_381();
    let pk = Bls12381G2Affine::from_bytes(pk_mint.clone());
    bls.g2_is_on_curve(&pk) && bls.g2_is_in_subgroup(&pk)
}

/// Verifies the unblinded mint signature `S` over `H(nullifier)`.
///
/// `s` is attacker-controlled bytes, so it is subgroup-checked before it
/// reaches the pairing: without that check a small-subgroup point could
/// satisfy the pairing equation without the mint's key. `pk_mint` needs no
/// check here — [`is_valid_mint_pk`] already vetted it at construction.
pub fn verify_blind_signature(
    env: &Env,
    s: &BytesN<96>,
    nullifier: &BytesN<32>,
    pk_mint: &BytesN<192>,
) -> bool {
    let bls = env.crypto().bls12_381();

    let sig = Bls12381G1Affine::from_bytes(s.clone());
    if !bls.g1_is_on_curve(&sig) || !bls.g1_is_in_subgroup(&sig) {
        return false;
    }

    let pk = Bls12381G2Affine::from_bytes(pk_mint.clone());
    let neg_g2 = Bls12381G2Affine::from_bytes(BytesN::from_array(env, &NEG_G2_GENERATOR));
    let y = hash_nullifier_to_g1(env, nullifier);

    // e(S, -G2) * e(Y, PK) == 1  <=>  e(S, G2) == e(Y, PK)
    bls.pairing_check(vec![env, sig, y], vec![env, neg_g2, pk])
}
