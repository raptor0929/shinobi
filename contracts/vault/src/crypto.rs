//! BLS12-381 blind-signature verification.
//!
//! The vault verifies one algebraic statement at redemption time:
//!
//! ```text
//!   e(S, G2) == e(H(nullifier), PK_mint)
//! ```
//!
//! where `S` is the unblinded mint signature and `H` is RFC 9380 hash-to-curve
//! into G1. Rearranged for a single multi-pairing call:
//!
//! ```text
//!   e(S, -G2) * e(H(nullifier), PK_mint) == 1
//! ```
//!
//! Everything here is a host function call. Unlike the EVM original, there is
//! no in-contract try-and-increment loop and no modexp — `hash_to_g1` is a
//! native Soroban host function, so mapping a nullifier onto the curve is one
//! call with a constant, metered cost.

use soroban_sdk::{
    crypto::bls12_381::{Bls12381G1Affine, Bls12381G2Affine},
    vec, Bytes, BytesN, Env,
};

/// Domain separation tag for the nullifier hash-to-curve, per RFC 9380 §3.1.
///
/// The `CPP-V1` prefix scopes the tag to this protocol version so a signature
/// produced for a different suite can never be replayed here. Off-chain
/// clients MUST use this exact byte string.
pub const HASH_TO_G1_DST: &[u8] = b"CPP-V1-CS01-with-BLS12381G1_XMD:SHA-256_SSWU_RO_";

/// Domain prefix for the redemption message signed by the spend key.
pub const REDEEM_DOMAIN: &[u8] = b"CPP-V1-REDEEM";

